  void ApplyRhTranspose(const Vector1& Uh, Vector1& Vh)
  {
    for (int i = 0; i <= r; i++)
      for (int j = 0; j <= r; j++)
	uloc(i, j) = Uh(NumNodes(i,j));
    
    MltAdd(1.0, SeldonTrans, GradPhi, SeldonNoTrans, uloc, 0.0, vx);
    MltAdd(1.0, SeldonNoTrans, uloc, SeldonNoTrans, GradPhi, 0.0, vy);
    
    for (int i = 0; i <= r; i++)
      for (int j = 0; j <= r; j++)
	{
	  Vh(2*NumNodes(i,j)) = vx(i, j);
	  Vh(2*NumNodes(i,j)+1) = vy(i, j);
	}
  }

  template<class Vector1>
  void ApplyRh(const Vector1& Vh, Vector1& Uh)
  {
    typedef typename Vector1::value_type Complexe;
    
    for (int i = 0; i <= r; i++)
      for (int j = 0; j <= r; j++)
	{
	  vx(i, j) = Vh(2*NumNodes(i,j));
	  vy(i, j) = Vh(2*NumNodes(i,j)+1);
	}
    
    MltAdd(1.0, SeldonNoTrans, GradPhi, SeldonNoTrans, vx, 0.0, uloc);
    MltAdd(1.0, SeldonNoTrans, vy, SeldonTrans, GradPhi, 1.0, uloc);
    
    for (int i = 0; i <= r; i++)
      for (int j = 0; j <= r; j++)
	Uh(NumNodes(i,j)) = uloc(i, j);
  }
  

