template<int i, int j, int r>
class SquareNumNodes2D
{
public :
  static Real_wp dphi;
  
  enum
    {
      num = (i==r)*(j==0) + 2*(i==r)*(j==r) + 3*(i==0)*(j==r)
      + (3+i)*(i >= 1)*(i < r)*(j==0) + (3+(r-1)+j)*(j >= 1)*(j < r)*(i==r)
      + (3+2*(r-1)+r-i)*(i >= 1)*(i < r)*(j==r) + (3+3*(r-1)+r-j)*(j >= 1)*(j < r)*(i==0)
      + (4*r + (i-1)*(r-1) + j-1)*(i >= 1)*(i < r)*(j >= 1)*(j < r)
    };
};

template<int i, int j, int r>
Real_wp SquareNumNodes2D<i, j, r>::dphi(0);

template<int m, int i, int j, int r>
class QuadLobattoLoop3
{
public :
  template<class Vector1>
  static inline void EvalVx(const Vector1& Uh, Vector1& Vh)
  {
    Vh(2*SquareNumNodes2D<i, j, r>::num)
      // += SquareLobatto<r>::GradPhi(m, i)*Uh(SquareNumNodes2D<m, j, r>::num);
      += SquareNumNodes2D<m, i, r>::dphi*Uh(SquareNumNodes2D<m, j, r>::num);
    QuadLobattoLoop3<m-1, i, j, r>::EvalVx(Uh, Vh);
  }

  template<class Vector1>
  static inline void EvalVy(const Vector1& Uh, Vector1& Vh)
  {
    Vh(2*SquareNumNodes2D<i, j, r>::num + 1)
      // += SquareLobatto<r>::GradPhi(m,j)*Uh(SquareNumNodes2D<i, m, r>::num);
      += SquareNumNodes2D<m, j, r>::dphi*Uh(SquareNumNodes2D<i, m, r>::num);
    QuadLobattoLoop3<m-1, i, j, r>::EvalVy(Uh, Vh);
  }
  
  template<class Vector1>
  static inline void EvalU(const Vector1& Vh, Vector1& Uh)
  {
    Uh(SquareNumNodes2D<i, j, r>::num)
      += SquareNumNodes2D<i, m, r>::dphi*Vh(2*SquareNumNodes2D<m, j, r>::num)
      + SquareNumNodes2D<j, m, r>::dphi*Vh(2*SquareNumNodes2D<i, m, r>::num +1);
    //+= SquareLobatto<r>::GradPhi(i, m)*Vh(2*SquareNumNodes2D<m, j, r>::num)
    //+ SquareLobatto<r>::GradPhi(j, m)*Vh(2*SquareNumNodes2D<i, m, r>::num +1);
    QuadLobattoLoop3<m-1, i, j, r>::EvalU(Vh, Uh);
  }

};

