  //! LU factorisation of indefinite unsymmetric matrices with partial pivoting
  /*!
    \param[inout] A on input, original matrix; on output, LU factors
    \param[inout] IPivot pivot numbers
    \param[in] exemple_reel any real number
    \param[in] zero zero (real or complex depending on the type of T)
    \param[in] one one (real or complex depending on the type of T)
   */
  template<class T, class Storage, class Allocator>
  void GetLU(Matrix<T, General, Storage, Allocator>& A, IVect& IPivot,
	     LapackInfo& info_)
  {
    T zero, one; SetComplexZero(zero); SetComplexOne(one);
    int m = A.GetM();
    int n = A.GetN();
    IPivot.Reallocate(n);
    
    // Quick return if possible
    if ((m==0)||(n==0)) 
      return;
    
    typename ClassComplexType<T>::Treal modulus_coef, tmp_real;
    T tmp_cpx; int jp, info=0;
    
    for (int j = 0; j < min(m,n); j++)
      {
	// we search maximum of the column j, it is the pivot
	jp = j; modulus_coef = abs(A(j,j));
	for (int k = j+1; k < m; k++)
	  {
	    tmp_real = abs(A(k, j));
	    if (tmp_real > modulus_coef)
	      {
		jp = k;
		modulus_coef = tmp_real;
	      }
	  }
	
	IPivot(j) = jp+1;
	if (A(jp,j) != zero)
	  {
	    // we don't have singularity
	    // we swap row j with row jp
	    if (jp != j)
	      {
		for (int k = 0; k < n; k++)
		  {
		    tmp_cpx = A(j, k);
		    A(j, k) = A(jp, k);
		    A(jp, k) = tmp_cpx;
		  }
	      }
	    
	    // we put coefficients of Lower Matrix L
	    if (j < m)
	      { 
		tmp_cpx = one/A(j, j);
		for (int k = j+1; k < m; k++)
		  A(k, j) *= tmp_cpx;
		
		A(j, j) = tmp_cpx;
	      }
	  }
	else if (info==0)
	  {
	    // singularity on row j
	    info = j+1;
	    cout<<"Matrix is singular"<<endl;
	    abort();	    
	  }
	
	// we modify row j+1 until m 
	if (j < min(m, n))
	  {
	    for (int k = j+1; k < m; k++)
	      for (int i = j+1; i < n; i++)
		A(k, i) -= A(k, j)*A(j, i);
	  }
      }
  }
  
  
  //! Resolution of A x = b, by using LU factorisation of A
  /*!
    \param[in] TransA if SeldonNoTrans, resolution of A x = b
                      if SeldonTrans, resolution of A^T x = b
    \param[in] A factorisation of matrix (generated by GetLU)
    \param[in] IPivot pivot numbers (generated by GetLU)
    \param[inout] b on input, right hand side; on output, solution of A x = b
   */
  template<class T, class Allocator,
           class Storage, class Prop, class Allocator2>
  void SolveLuVector(const SeldonTranspose& TransA,
                     const Matrix<T, General, Storage, Allocator>& A,
                     const IVect& IPivot, Vector<T, Prop, Allocator2>& b,
		     LapackInfo& info_)
  {
    int n = A.GetM();
    if (n <= 0)
      return;
    
    if (TransA.Trans())
      {
        int l; T tmp;
        // we solve now U^T x = b
        // by columns
        for (int k = 0; k < n; k++)
          {
            for (l = 0; l < k; l++)
              b(k) -= A(l, k)*b(l);
            
            b(k) *= A(k, k);
          }
        
        // we solve L^T x = b 
        // by columns
        for (int k = n-2; k >= 0; k--)
          {
            for (l = (k+1); l < n; l++)
              b(k) -= A(l, k)*b(l); 
          }     

        for (int k = n-2; k >= 0; k--)
          {
            l = IPivot(k)-1;
            tmp = b(l);
            // we swap if necessary
            if (l != k)
              {
                b(l) = b(k);
                b(k) = tmp;
              }
          }
      }
    else
      {
        int l; T tmp;
        // we solve Lx = b 
        // by columns
        for (int k = 0; k < (n-1); k++)
          {
            l = IPivot(k)-1;
            tmp = b(l);
            // we swap if necessary
            if (l != k)
              {
                b(l) = b(k);
                b(k) = tmp;
              }
          }
        
        for (int k = 0; k < (n-1); k++)
          {
            tmp = b(k);
            for ( l = (k+1); l < n; l++)
              b(l) -= A(l, k)*tmp; 
          }
        
        // we solve now Ux = b
        // by columns
        for (int k = (n-1); k >= 0; k--)
          {
            b(k) *= A(k, k);
            tmp = b(k);
            for ( l = 0; l < k; l++)
              b(l) -= A(l, k)*tmp;
          }
      }
  }
    
  
