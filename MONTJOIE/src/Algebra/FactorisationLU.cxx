  //! replaces matrix A by its Cholesky factorisation
  template<class T, class Prop, class Storage, class Allocator>
  void GetCholesky(Matrix<T, Prop, Storage, Allocator>& A, LapackInfo& info)
  {
    int n = A.GetM();
    T val, invVal, vloc, one, zero;
    SetComplexOne(one);
    SetComplexZero(zero);
    for (int j = 0; j < n; j++)
      {
	// diagonal element
	val = A(j, j);
	for (int k = 0; k < j; k++)
	  val -= A(k, j)*A(k, j);
	
        if (val <= zero)
	  {
            cout << "Error during Cholesky factorization " << endl;
            cout << "Matrix must be definite positive " << endl;
            cout << "but diagonal element of row " << j 
                 << " is equal to " << val << endl;

	    throw WrongArgument("GetCholesky", "Negative diagonal");
          }
	
	val = sqrt(val);
	A.Get(j, j) = val;
	invVal = one/val;
	
	// other elements of the row
	for (int k = j+1; k < n; k++)
	  {
	    vloc = A(j, k);
	    for (int m = 0; m < j; m++)
	      vloc -= A(k, m)*A(m, j);
	    
	    A.Get(j, k) = vloc*invVal;
	  }
      }
  }


  //! replaces matrix A by its Cholesky factorisation (Hermitian matrix)
  template<class T, class Prop, class Storage, class Allocator>
  void GetCholesky(Matrix<complex<T>, Prop, Storage, Allocator>& A, LapackInfo& info)
  {
    int n = A.GetM();
    T val, invVal, one, zero;
    SetComplexOne(one);
    SetComplexZero(zero);
    complex<T> vloc;
    for (int j = 0; j < n; j++)
      {
	// diagonal element
	val = real(A(j, j));
	for (int k = 0; k < j; k++)
	  val -= absSquare(A(k, j));
	
        if (val <= zero)
	  {
            cout << "Error during Cholesky factorization " << endl;
            cout << "Matrix must be definite positive " << endl;
            cout << "but diagonal element of row " << j 
                 << " is equal to " << val << endl;

	    throw WrongArgument("GetCholesky", "Negative diagonal");
          }
	
	val = sqrt(val);
	A.Get(j, j) = complex<T>(val, zero);
	invVal = one/val;
	
	// other elements of the row
	for (int k = j+1; k < n; k++)
	  {
	    vloc = A(j, k);
	    for (int m = 0; m < j; m++)
              vloc -= A(m, k)*conjugate(A(m, j));
              	    
	    A.Get(j, k) = vloc*invVal;
	  }
      }
  }
  
  
  //! when A = L L^T, solves L x = b or L^T x = b
  /*!
    \param[in] TransA SeldonNoTrans for solving L x = b, SeldonTrans for L^T x = b
    \param[in] A Cholesky factorisation of matrix A
    \param[inout] x on input, right hand side b; on output, solution x
    We assume here that GetCholesky has been called before to generate
    the Cholesky factorisation of the original matrix
   */
  template<class T, class Prop,
           class Storage, class Allocator,
	   class T2, class Storage2, class Allocator2>
  void SolveCholesky(const SeldonTranspose& TransA,
		     const Matrix<T, Prop, Storage, Allocator>& A,
		     Vector<T2, Storage2, Allocator2>& x, LapackInfo& info)
  {
    int n = A.GetM();
    if (n <= 0)
      return;
    
    if (TransA.Trans())
      {
        // we solve L^T x = x
	for (int i = n-1; i >= 0; i--) 
          {
            T2 val = x(i);
            for (int k = i+1; k < n; k++)
	      val -= A(i, k)*x(k);
                          
            x(i) = val/A(i, i);
          }
      }
    else
      {
        // we solve L x = x
        for (int i = 0; i < n; i++) 
          {
            x(i) /= A(i, i);
            for (int k = i+1; k < n; k++)
	      x(k) -= A(i, k)*x(i);
	    
          }
      }
  }
  
  
