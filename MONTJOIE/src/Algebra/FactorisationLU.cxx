  //! replaces matrix A by QR factorisation
  /*!
    \param[inout] A on input, original matrix; on output, QR factorisation
    \param[out] tau intermediary array needed to SolveQR
   */
  template<class T, class Prop, class Storage, class Allocator, class Allocator2>
  void GetQR(Matrix<T, Prop, Storage, Allocator>& A, Vector<T, VectFull, Allocator2>& tau,
	     LapackInfo& info)
  {
    T one, zero; SetComplexOne(one);
    SetComplexZero(zero);
    typedef typename ClassComplexType<T>::Treal Treal;
    Treal normU, normUp, normN, invNormN;
    T v1, prod_scal, alpha, n1;
    SetComplexZero(normU);
    int m = A.GetM();
    int n = A.GetN();
    tau.Reallocate(n); tau.Fill(1);
    for (int i = 0; i < n; i++)
      {
        // U = (a_ii, a_{i+1,i}, ..., a_{i, n})
        // V = (-signe(a_ii) || U ||, 0, 0, ..., 0)
        // N = (U-V)/ || U - V ||
        normUp = 0;
        for (int k = i+1; k < m; k++)
          normUp += absSquare(A(k, i));
        
        if (normUp > Treal(0))
          {
            // norm of U
            normU = sqrt(normUp + absSquare(A(i, i)));
	    SetComplexReal(normU, v1);
	    if (A(i, i) != zero)
	      v1 *= -A(i, i) / abs(A(i, i));
	    
            // norm of N and first component of N
            alpha = A(i, i) - v1; 
            normN = sqrt(normUp + absSquare(alpha));
            invNormN = Treal(1)/normN;
            n1 = alpha*invNormN;
                        
            // first-column is replaced with normale except first component
            A(i, i) = v1;
            for (int k = i+1; k < m; k++)
              A(k, i) *= invNormN;
            
            // we apply H = I - 2 N N^T to other sub-columns of A
            for (int j = i+1; j < n; j++)
              {
                // computation of C \cdot N
                prod_scal = A(i, j)*n1;
                for (int k = i+1; k < m; k++)
                  prod_scal += A(k, j)*A(k, i);
                
                prod_scal *= T(2);
                // we subtract - 2 N ( N^T cdot C )
                A(i, j) -= n1*prod_scal;
                for (int k = i+1; k < m; k++)
                  A(k, j) -= A(k, i)*prod_scal;
              }
            
            // first component of normale is stored in tau
            tau(i) = n1;
          }
      }
  }

  
  //! overwrites x by solution of Q R x = b
  /*!
    \param[in] A QR factorisation of a matrix
    \param[in] tau intermediary array produced by GetQR
    \param[inout] x on input, right hand side; on output, solution x
   */
  template<class T, class Prop, class Storage, class Allocator,
           class T2, class Allocator2, class Allocator3>
  void SolveQR(const Matrix<T, Prop, Storage, Allocator>& A,
               const Vector<T, VectFull, Allocator2>& tau,
               Vector<T2, VectFull, Allocator3>& X, LapackInfo& info)
  {
    T prod_scal, val, one;
    SetComplexOne(one);

    int m = A.GetM();
    int n = A.GetN();
    // computation of Q^T x
    for (int i = 0; i < n; i++)
      {
        // we overwrite X with X - 2 N N^t X
        if (tau(i) != one)
          {
            prod_scal = tau(i)*X(i);
            for (int j = i+1; j < m; j++)
              prod_scal += A(j, i)*X(j);
            
            prod_scal *= T(2);
            X(i) -= prod_scal*tau(i);
            for (int j = i+1; j < m; j++)
              X(j) -= prod_scal*A(j, i);
          }
      }

    // now resolution of R x = Q^T x
    X.Resize(n);
    for (int i = n-1; i >= 0; i--)
      {
        val = X(i);
        for (int j = i+1; j < n; j++)
          val -= A(i, j)*X(j);
        
        X(i) = val/A(i, i);        
      }
  }
  
  
  //! Multiplies X by Q from QR factorisation of A
  /*!
    \param[in] trans SeldonNoTrans or SeldonTrans
    \param[in] A QR factorisation of the original matrix A
    \param[in] tau intermediary array filled by GetQR
    \param[inout] X on input X, on output Q X or Q^T X
    Once QR factorisation of A (A = Q R) has been performed (by calling GetQR),
    this function overwrites X by Q X or Q^T X if trans is equal to class_SeldonTrans
   */
  template<class IsTranspose, class T, class Prop,
	   class Storage, class Allocator,
           class T2, class Allocator2, class Allocator3>
  void MltQ_FromQR(const IsTranspose& trans,
		   const Matrix<T, Prop, Storage, Allocator>& A,
		   const Vector<T, VectFull, Allocator2>& tau,
		   Vector<T2, VectFull, Allocator3>& X, LapackInfo& info)
  {
    if (!trans.Trans())
      {
	abort();
      }
    
    T prod_scal, val, one;
    SetComplexOne(one);
    int m = A.GetM();
    int n = A.GetN();
    // computation of Q^T x
    for (int i = 0; i < n; i++)
      {
        // we overwrite X with X - 2 N N^t X
        if (tau(i) != one)
          {
            prod_scal = tau(i)*X(i);
            for (int j = i+1; j < m; j++)
              prod_scal += A(j, i)*X(j);
            
            prod_scal *= T(2);
            X(i) -= prod_scal*tau(i);
            for (int j = i+1; j < m; j++)
              X(j) -= prod_scal*A(j, i);
          }
            
      }
  }
  
  
