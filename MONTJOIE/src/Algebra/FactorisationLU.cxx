  //! Computes Householder transformation for a single vector
  /*!
    The vector U is replaced by the normale defining the Householder transformation
    H = I - 2 N N^T
    The function returns the first component of vector V
   */
  template<class T>
  T GetHouseholderNormale(Vector<T>& U)
  {
    if (U.GetM() <= 0)
      return T(0);
    
    // the same kind of computation is made in GetQR
    
    // we start from a vector U:
    // U = (U_0, U_{1}, ..., U_{n-1})

    // and we want to find an orthogonal transformation into a vector V:
    // V = (-sign(U_0) || U ||, 0, 0, ..., 0)

    // sign(U_0) is put to maximize the first component of U-V

    // The transformation to transform U into V is the Householder transformation
    // H = I - 2 N N^T  where N is the normale defined as
    // N = (U-V)/ || U - V ||
    typedef typename ClassComplexType<T>::Treal Treal;
    Treal normUp = 0;
    for (int k = 1; k < U.GetM(); k++)
      normUp += absSquare(U(k));
    
    T zero; SetComplexZero(zero);
    T v1 = U(0);
    if (normUp > Treal(0))
      {
	// norm of U
	Treal normU = sqrt(normUp + absSquare(U(0)));
	// first component of V
	SetComplexReal(normU, v1);
	if (U(0) != zero)
	  v1 *= -U(0) / abs(U(0));
	
	// norm of N and first component of N
	T alpha = U(0) - v1; 
	Treal normN = sqrt(normUp + absSquare(alpha));
	Treal invNormN = Treal(1)/normN;
	T n1 = alpha*invNormN;
	
	// U is replaced by N
	U(0) = n1;
	for (int k = 1; k < U.GetM(); k++)
	  U(k) *= invNormN;	
      }
    else
      {
	U.Zero();
	SetComplexOne(U(0));
      }
    
    // we return the first component of V
    return v1;
  }

  
  //! Q is orthogonalized with respect to householder transformations stored in H
  /*!
    Householder transformation for Q(size:end) is computed and stored in H(size)
    Householder transformations are applied to the canonical vector [0, .., 1, 0, .., 0]
    such that Q will be orthogonalized with respect to Householder transformations stored in H
   */
  template<class T>
  void GetReorthogonalization(Vector<Vector<T> >& H, int size, Vector<T>& Q)
  {
    T one; SetComplexOne(one);
    int dim = Q.GetM() - size;
    H(size).Reallocate(dim);
    if (dim > 1)
      {
	for (int i = 0; i < dim; i++)
	  H(size)(i) = Q(i+size);
	
	GetHouseholderNormale(H(size));
      }
    else
      H(size) = one;

    Q.Zero();
    Q(size) = one;
    for (int i = size; i >= 0; i--)
      ApplyHouseholderTransformation(H(i), i, Q);
  }
  

  //! Applies Householder transformation to a vector
  /*!
    Householder transformation is given as H = I - 2 N N^H
    Only the normale N is provided as input array
    The transformation is applied to X(k:end)
   */
  template<class T>
  void ApplyHouseholderTransformation(const Vector<T>& N, int k, Vector<T>& X)
  {
    // scalar product with N
    T x_scal_N;
    SetComplexZero(x_scal_N);
    for (int i = k; i < X.GetM(); i++)
      x_scal_N += conjugate(N(i-k))*X(i);

    // replacing X by (X - 2 (N \cdot X) X)
    x_scal_N *= 2;
    for (int i = k; i < X.GetM(); i++)
      X(i) -= x_scal_N*N(i-k);    
    
  }
  
  
