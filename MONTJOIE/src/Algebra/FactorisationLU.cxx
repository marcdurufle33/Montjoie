  void MltUpper(const Matrix<T, General, Storage, Allocator1>& A,
                  Vector<T, VectFull, Allocator2>& x)
  {
    T vloc;
    int n = x.GetM();
    for (int i = 0; i < n; i++)
      {
        vloc = A(i, i)*x(i);
        for (int j = i+1; j < n; j++)
          vloc += A(i, j)*x(j);
        
        x(i) = vloc;
      }
  }


