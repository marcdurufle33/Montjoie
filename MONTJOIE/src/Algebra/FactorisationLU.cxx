  //! LU factorisation of indefinite unsymmetric matrices with partial pivoting
  /*!
    \param[inout] A on input, original matrix; on output, LU factors
    \param[inout] IPivot pivot numbers
    \param[in] exemple_reel any real number
    \param[in] zero zero (real or complex depending on the type of T)
    \param[in] one one (real or complex depending on the type of T)
    we compute a LDL^t factorization with partial symmetric pivoting
    D is a block diagonal matrix with 2x2 and 1x1 blocks
   */
  template<class T, class Storage, class Allocator>
  void GetLU(Matrix<T, Symmetric, Storage, Allocator>& A, IVect& IPivot,
	     LapackInfo& info_)   
  {
    T zero, one; SetComplexZero(zero); SetComplexOne(one);
    int n = A.GetN();
    IPivot.Reallocate(n);
    // Quick return if possible
    if (n == 0) 
      return;
    
    typedef typename ClassComplexType<T>::Treal reel;
    typename ClassComplexType<T>::Treal modulus_coef, rowmax, colmax, alpha, sevten;
    sevten = reel(17);
    alpha = (reel(1)+sqrt(sevten))/8;
    T tmp_cpx, d11, d22, d21, wk, wkp1;
    reel zero_r(0); 
    int info = 0;
    
    // k is the main loop index, increasing from 1 to n in steps of
    // 1 or 2
    int i,k = 0, j = 0, kc = 0,knc, npp = A.GetDataSize();
    int kstep , kp, kx, kpc, kk, imax(0); 
    T* a_ptr = A.GetData();
    while (k < n)
      {
	knc = kc; kstep = 1;
	// Determine rows and columns to be interchanged and whether
	// a 1-by-1 or 2-by-2 pivot block will be used
	modulus_coef = abs(a_ptr[kc]);
	// IMAX is the row-index of the largest off-diagonal element in
	// column K, and COLMAX is its absolute value
	if (k < (n-1))
	  {
	    colmax = zero_r;
	    for ( j = 1; j < (n-k); j++)
	      if (abs(a_ptr[kc+j]) > colmax)
		{
		  imax = k + j;
		  colmax = abs(a_ptr[kc+j]);
		}
	  }
	else
	  colmax = zero_r;
	
	if (max(modulus_coef,colmax)==zero_r)
	  {
	    // Column K is zero: set INFO and continue
	    if (info==0)
	      info = k+1;
	    kp = k;
	  }
	else
	  {
	    if (modulus_coef >= (alpha*colmax))
	      {
		// no interchange, use 1-by-1 pivot block
		kp = k;
	      }
	    else
	      {
		// JMAX is the column-index of the largest off-diagonal
		// element in row IMAX, and ROWMAX is its absolute value
		rowmax = zero_r;
		kx = kc + imax - k;
		for ( j=k ; j<=(imax-1) ; j++)
		  {
		    if (abs(a_ptr[kx]) > rowmax)
		      rowmax = abs(a_ptr[kx]);
		
		    kx += n-1-j;
		  }
		kpc = npp - (n-imax)*(n-imax+1) / 2;
		if (imax<(n-1))
		  {
		    for ( j = 1; j < (n-imax); j++)
		      {
			if (abs(a_ptr[kpc+j]) > rowmax)
			  rowmax = abs(a_ptr[kpc+j]);
		      }
		  }
		if (modulus_coef >= (alpha*colmax*(colmax/rowmax)) )
		  {
		    // no interchange, use 1-by-1 pivot block
		    kp = k;
		  }
		else if (abs(a_ptr[kpc]) >= (alpha*rowmax) )
		  {
		    // interchange rows and columns K and IMAX, use 1-by-1
		    // pivot block
		    kp = imax;
		  }
		else
		  {
		    // interchange rows and columns K+1 and IMAX, use 2-by-2
		    // pivot block
		    kp = imax;
		    kstep = 2;
		  }    
	      }
	    kk = k + kstep - 1;
	    if (kstep==2)
	      knc += n-k;
	    if ( kp != kk )
	      {
		// Interchange rows and columns KK and KP in the trailing
		// submatrix A(k:n,k:n)
		if (kp<(n-1))
		  {
		    for ( j = 1; j < (n-kp); j++)
		      {
			tmp_cpx = a_ptr[kpc+j];
			a_ptr[kpc+j] = a_ptr[knc+kp-kk+j];
			a_ptr[knc+kp-kk+j] = tmp_cpx;
		      }
		  }
		kx = knc+kp-kk;
		for ( j = (kk+1); j < kp; j++)
		  {
		    kx += n-j;
		    tmp_cpx = a_ptr[knc+j-kk];
		    a_ptr[knc+j-kk] = a_ptr[kx];
		    a_ptr[kx] = tmp_cpx;
		  }
		tmp_cpx = a_ptr[knc];
		a_ptr[knc] = a_ptr[kpc];
		a_ptr[kpc] = tmp_cpx;
		if (kstep == 2)
		  {
		    tmp_cpx = a_ptr[kc+1];
		    a_ptr[kc+1] = a_ptr[kc+kp-k];
		    a_ptr[kc+kp-k] = tmp_cpx;
		  }
	      }
	    // Update the trailing submatrix
	    if (kstep == 1)
	      {
		// 1-by-1 pivot block D(k): column k now holds
		// W(k) = L(k)*D(k)
		// where L(k) is the k-th column of L
		if (k < (n-1))
		  {
		    // Perform a rank-1 update of A(k+1:n,k+1:n) as
		    // A := A - L(k)*D(k)*L(k)' = A - W(k)*(1/D(k))*W(k)'
		    d11 = one/a_ptr[kc];
		    
		    kk = kc+n-k;
		    for ( j = 1; j < (n-k); j++)
		      {
			if (a_ptr[kc+j] != zero )
			  {
			    tmp_cpx = d11*a_ptr[kc+j];
			    int l = kk;
			    for ( i = j; i < (n-k); i++)
			      a_ptr[l++] -= a_ptr[kc+i]*tmp_cpx;
			  }
			kk += n - k - j;
		      }
		    
		    // Store L(k) in column K
		    for ( j = 1; j < (n-k); j++)
		      a_ptr[kc+j] *= d11;
		  }
	      }
	    else
	      {
		// 2-by-2 pivot block D(k): columns K and K+1 now hold
		// ( W(k) W(k+1) ) = ( L(k) L(k+1) )*D(k)
		// where L(k) and L(k+1) are the k-th and (k+1)-th columns
		// of L
		if ( k < (n-2) )
		  {
		    // Perform a rank-2 update of A(k+2:n,k+2:n) as
		    // A := A - ( L(k) L(k+1) )*D(k)*( L(k) L(k+1) )'
		    //    = A - ( W(k) W(k+1) )*inv(D(k))*( W(k) W(k+1) )'
		    // where L(k) and L(k+1) are the k-th and (k+1)-th
		    // columns of L
		    d21 = a_ptr[k+1+k*(2*n-k-1)/2];
		    d11 = a_ptr[k+1+(k+1)*(2*n-k-2)/2]/d21;
		    d22 = a_ptr[k+k*(2*n-k-1)/2]/d21;
		    tmp_cpx = one/(d11*d22-one);
		    d21 = tmp_cpx/d21;
		    for ( j = (k+2); j < n; j++)
		      {
			wk = d21*( d11*a_ptr[ j + k*(2*n-k-1)/2 ]
                                   - a_ptr[ j + (k+1)*(2*n-k-2)/2 ] );
			
                        wkp1 = d21*( d22*a_ptr[ j + (k+1)*(2*n-k-2)/2 ]
                                     - a_ptr[ j + k*(2*n-k-1)/2 ] );
			
                        for ( i = j; i < n; i++)
                          a_ptr[i+j*(2*n-j-1)/2] -= a_ptr[i+k*(2*n-k-1)/2 ]*wk
                            + a_ptr[i+(k+1)*(2*n-k-2)/2 ]*wkp1;

			a_ptr[j + k*(2*n-k-1)/2 ] = wk;
			a_ptr[j + (k+1)*(2*n-k-2)/2 ] = wkp1;
		      }
		  }
	      }
	  }
        
	// Store details of the interchanges in IPivot
	if (kstep==1)
	  IPivot(k) = kp+1;
	else
	  {
	    IPivot(k) = -(kp+1);
	    IPivot(k+1) = -(kp+1);
	  }
        
	// Increase K and return to the start of the main loop
	k += kstep;
	kc = knc + n - k + 1;
      }
  }
  
  
  //! Resolution of A x = b, by using LU factorisation of A
  /*!
    \param[in] A factorisation of matrix (generated by GetLU)
    \param[in] IPivot pivot numbers (generated by GetLU)
    \param[inout] b on input, right hand side; on output, solution of A x = b
    This method is written for symmetric matrices (real or complex)
   */
  template<class T, class Allocator, class Storage, class Prop, class Allocator2>
  void SolveLuVector(const Matrix<T, Symmetric, Storage, Allocator>& A,
                     const IVect& IPivot, Vector<T, Prop, Allocator2>& b,
		     LapackInfo& info)
  {
    int n = A.GetM();
    if (n <= 0)
      return;
    
    // Solve A*X = B, where A = L*D*L'.
    // First solve L*D*X = B, overwriting B with X.
    
    // k is the main loop index, increasing from 1 to n in steps of
    // 1 or 2, depending on the size of the diagonal blocks.
    int k = 0, kc = 0, j = 0, kp;
    T tmp, akm1k, akm1, ak, denom, bkm1, bk, one;
    SetComplexOne(one);
    T* a_ptr = A.GetData();
    while (k < n)
      {
	if (IPivot(k) > 0)
	  {
	    // 1 x 1 diagonal block
	    //
	    // Interchange rows k and IPivot(k).
	    kp = IPivot(k) - 1;
	    if (kp != k)
	      {
		tmp = b(k);
		b(k) = b(kp);
		b(kp) = tmp;
	      }
	    
	    if (k < (n-1))
	      {
		for ( j = 1; j < (n-k); j++)
		  b(k+j) -= a_ptr[kc+j]*b(k);
	      }
	    b(k) /= a_ptr[kc];
	    kc += n-k;
	    k++;
	  }
	else
	  {
	    // 2 x 2 diagonal block
	    //
	    // Interchange rows k+1 and -IPivot(k).
	    kp = -IPivot(k) - 1;
	    if (kp != (k+1))
	      {
		tmp = b(k+1);
		b(k+1) = b(kp);
		b(kp) = tmp;
	      }
	    if (k<(n-1))
	      {
		for ( j = 1; j < (n-k-1); j++)
		  b(k+j+1) -= a_ptr[kc+j+1]*b(k);
		
		for ( j = 1; j < (n-k-1); j++)
		  b(k+j+1) -= a_ptr[kc+n-k+j]*b(k+1);
	      }
	    akm1k = a_ptr[kc+1];
	    akm1 = a_ptr[kc]/akm1k;
	    ak = a_ptr[kc+n-k]/akm1k;
	    denom = akm1*ak - one;
	    bkm1 = b(k)/akm1k;
	    bk = b(k+1)/akm1k;
	    b(k) = (ak*bkm1-bk)/denom;
	    b(k+1) = (akm1*bk-bkm1)/denom;
	    kc += 2*(n-k-1) + 1;
	    k += 2;
	  }
	
      }
    k = n-1;
    kc = A.GetDataSize();
    // Next solve L'*X = B, overwriting B with X.
    
    // k is the main loop index, decreasing from n to 1 in steps of
    // 1 or 2, depending on the size of the diagonal blocks.
    
    while (k >= 0)
      {
	kc -= n-k;
	if (IPivot(k) > 0)
	  {
	    // 1 x 1 diagonal block
	    
	    // Multiply by inv(L'(K)), where L(K) is the transformation
	    // stored in column K of A.
	    if (k < (n-1))
	      {
		for ( j = 1; j < (n-k); j++)
		  b(k) -= a_ptr[kc+j]*b(k+j);
	      }
	    kp = IPivot(k) - 1;
	    if (kp != k)
	      {
		tmp = b(k);
		b(k) = b(kp);
		b(kp) = tmp;
	      }
	    k--;
	  }
	else
	  {
	    // 2 x 2 diagonal block
	    
	    // Multiply by inv(L'(K-1)), where L(K-1) is the transformation
	    // stored in columns K-1 and K of A.
	    if (k < (n-1))
	      {
		for ( j = 1; j < (n-k); j++)
		  b(k) -= a_ptr[kc+j]*b(k+j);
		
		kp = kc-(n-k);
		for ( j = 1; j < (n-k); j++)
		  b(k-1) -= a_ptr[kp+j]*b(k+j);
	      }
	    // Interchange rows K and -IPIV(K).
	    kp = -IPivot(k)-1;
	    if (kp != k)
	      {
		tmp = b(k);
		b(k) = b(kp);
		b(kp) = tmp;
	      }
	    kc -= (n-k+1);
	    k -= 2;
	  }
      }
  }
  

  //! A is replaced by its inverse
  /*!
    \param[inout] A on input, original matrix; on output, inverse
    The matrix can be real or complex symmetric
   */
  template<class T, class Allocator>
  void GetInverse(Matrix<T, Symmetric, RowSymPacked, Allocator>& A, LapackInfo& info)
  {
    // factorisation of matrix A
    IVect IPivot;
    GetLU(A, IPivot);
    
    int n = A.GetM();
    T* ap = A.GetData();
    T zero, one, temp1, temp2, prod_scal;
    T valT, valD, ak, akp1, akkp1;
    SetComplexOne(one);
    SetComplexZero(zero);
    
    // Compute inv(A) from the factorization A = L*D*L'.
    
    // K is the main loop index, increasing from 1 to N in steps of
    // 1 or 2, depending on the size of the diagonal blocks.
    int k = n-1;
    int npp = A.GetDataSize();
    int kc = npp - 1;
    int kstep = 0;
    Vector<T> work(n);
    work.Fill(0);
    while (k >= 0)
      {
        int kcnext = kc - (n-k+1);
        
        if (IPivot(k) > 0)
          {
            // 1 x 1 diagonal block
            // invert the diagonal block
            ap[kc] = one / ap[kc];
            
            // Compute column K of the inverse.
            if (k < n-1)
              {
                for (int i = 1; i < n-k; i++)
                  {
                    work(i-1) = ap[kc+i];
                    ap[kc+i] = zero;
                  }
                
                int kk = kc+n-1-k+1;
                prod_scal = zero;
                for (int j = 0; j < n-1-k; j++)
                  {
                    temp1 = -work(j);
                    temp2 = zero;
                    ap[kc+j+1] += temp1*ap[kk];
                    int k2 = kk + 1;
                    for (int i = j+1; i < n-1-k; i++)
                      {
                        ap[kc+i+1] += temp1*ap[k2];
                        temp2 += ap[k2]*work(i);
                        k2++;
                      }
                    
                    ap[kc+j+1] -= temp2;
                    prod_scal += ap[kc+j+1]*work(j);
                    kk += n-1-k-j;
                  }
                
                ap[kc] -= prod_scal;
              }
            
            kstep = 1;
          }
        else
          {

            // 2 x 2 diagonal block
            
            // Invert the diagonal block.
            valT = ap[kcnext+1];
            ak = ap[kcnext] / valT;
            akp1 = ap[kc] / valT;
            akkp1 = ap[kcnext+1] / valT;
            valD = valT*( ak*akp1-one );
            ap[kcnext] = akp1 / valD;
            ap[kc] = ak / valD;
            ap[kcnext+1] = -akkp1 / valD;
            
            // Compute columns K-1 and K of the inverse.
            if (k < n-1)
              {
                for (int i = 1; i < n-k; i++)
                  {
                    work(i-1) = ap[kc+i];
                    ap[kc+i] = zero;
                  }
                
                int kk = kc+n-1-k+1;
                prod_scal = zero;
                for (int j = 0; j < n-1-k; j++)
                  {
                    temp1 = -work(j);
                    temp2 = zero;
                    ap[kc+j+1] += temp1*ap[kk];
                    int k2 = kk + 1;
                    for (int i = j+1; i < n-1-k; i++)
                      {
                        ap[kc+i+1] += temp1*ap[k2];
                        temp2 += ap[k2]*work(i);
                        k2++;
                      }
                    
                    ap[kc+j+1] -= temp2;
                    prod_scal += ap[kc+j+1]*work(j);
                    kk += n-1-k-j;
                  }
                
                ap[kc] -= prod_scal;
                
                prod_scal = zero;
                for (int j = 0; j < n-1-k; j++)
                  prod_scal += ap[kc+1+j]*ap[kcnext+2+j];
                
                ap[kcnext+1] -= prod_scal;
                for (int i = 1; i < n-k; i++)
                  {
                    work(i-1) = ap[kcnext+1+i];
                    ap[kcnext+1+i] = zero;
                  }
                
                kk = kc+n-1-k+1;
                prod_scal = zero;
                for (int j = 0; j < n-1-k; j++)
                  {
                    temp1 = -work(j);
                    temp2 = zero;
                    ap[kcnext+j+2] += temp1*ap[kk];
                    int k2 = kk + 1;
                    for (int i = j+1; i < n-1-k; i++)
                      {
                        ap[kcnext+i+2] += temp1*ap[k2];
                        temp2 += ap[k2]*work(i);
                        k2++;
                      }
                    
                    ap[kcnext+j+2] -= temp2;
                    prod_scal += ap[kcnext+j+2]*work(j);
                    kk += n-1-k-j;
                  }
                
                ap[kcnext] -= prod_scal;
              }
            
            kstep = 2;
            kcnext -= n-1-k+3;
          }
        
        int kp = abs(IPivot(k)) - 1;
        if (kp != k)
          {
            // Interchange rows and columns K and KP in the trailing
            // submatrix A(k-1:n,k-1:n)
            
            int kpc = npp - (n-1-kp+1)*(n-1-kp+2) / 2;
            if (kp < n-1)
              for (int i = 0; i < n-1-kp; i++)
                {
                  temp1 = ap[kc+kp-k+i+1];
                  ap[kc+kp-k+i+1] = ap[kpc+i+1];
                  ap[kpc+i+1] = temp1;
                }
            
            int kx = kc + kp - k;
            for (int j = k+1; j <= kp-1; j++)
              {
                kx += n-1-j+1;
                temp1 = ap[kc+j-k];
                ap[kc+j-k] = ap[kx];
                ap[kx] = temp1;
              }
            
            temp1 = ap[kc];
            ap[kc] = ap[kpc];
            ap[kpc] = temp1;
            
            if (kstep == 2)
              {
                temp1 = ap[kc-(n-1)+k-1];
                ap[kc-(n-1)+k-1] = ap[kc-(n-1)+kp-1];
                ap[kc-(n-1)+kp-1] = temp1;
              }

          }
        
        k -= kstep;
        kc = kcnext;
      }
  }
  
  
  //! A is replaced by its inverse
  /*!
    \param[inout] A on input, original matrix; on output, inverse
    The matrix can be real or complex unsymmetric
   */
  template<class T, class Storage, class Allocator>
  void GetInverse(Matrix<T, General, Storage, Allocator>& A, LapackInfo& info)
  {
    // factorisation of matrix A
    IVect IPivot;
    GetLU(A, IPivot);
    
    // forming inverse of U
    int n = A.GetM();
    T one, zero, temp;
    SetComplexOne(one);
    SetComplexZero(zero);
    for (int i = 0; i < n; i++)
      {
        for (int k = i+1; k < n; k++)
          {
            temp = zero;
            for (int j = i; j < k; j++)
              temp -= A(i, j)*A(j, k);
            
            A(i, k) = temp*A(k, k);
          }        
      }
    
    // solving equation inv(A)*L = inv(U) for inv(A)
    Vector<T> work(n);
    work.Fill(0);
    for (int k = n-2; k >= 0; k--)
      {
        for (int i = k+1; i < n; i++)
          {
            work(i) = A(i, k);
            A(i, k) = zero;
          }
        
        // Compute current column of inv(A).
        for (int i = 0; i < n; i++)
          for (int j = k+1; j < n; j++)
            A(i, k) -= A(i, j)*work(j);
      }

    // Apply column interchanges.
    for (int j = n-2; j >= 0; j--)
      {
        int jp = IPivot(j)-1;
        if (jp != j)
          {
            for (int k = 0; k < n; k++)
              {
                temp = A(k, j);
                A(k, j) = A(k, jp);
                A(k, jp) = temp;
              }
          }
      }
  }


